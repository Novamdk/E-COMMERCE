const byName = new Map(
  Object.entries(STATES).map(([code, name]) => [name.toLowerCase().replace(/[^a-z]/g, ''), code]),
);

/**
 * "ca", "CA", "California" and "calif." style input to "CA"; null if unknown.
 * @param {string} value
 */
export function toStateCode(value) {
  const raw = String(value ?? '').trim();
  const upper = raw.toUpperCase();
  if (STATES[upper]) return upper;
  return byName.get(raw.toLowerCase().replace(/[^a-z]/g, '')) ?? null;
}
