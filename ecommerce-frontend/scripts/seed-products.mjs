/**
 * Writes supabase/seed.sql from src/data/products.json, so the products table
 * mirrors the catalog the site sells from. Run after changing the catalog:
 *   pnpm run db:seed   then paste supabase/seed.sql into the Supabase SQL editor.
 *
 * Existing stock numbers in the table are kept; only names and prices update.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const products = JSON.parse(readFileSync(`${root}src/data/products.json`, 'utf8'));

const text = (value) => (value == null ? 'null' : `'${String(value).replaceAll("'", "''")}'`);
const int = (value) => (Number.isInteger(value) ? String(value) : 'null');

const rows = products.map(
  (p) =>
    `  (${text(p.id)}, ${text(p.slug)}, ${text(p.title)}, ${int(p.price)}, ${int(p.compareAtPrice)})`,
);

const sql = `-- Generated by scripts/seed-products.mjs from src/data/products.json. Do not edit by hand.
insert into public.products (id, slug, title, price_cents, compare_at_cents)
values
${rows.join(',\n')}
on conflict (id) do update set
  slug = excluded.slug,
  title = excluded.title,
  price_cents = excluded.price_cents,
  compare_at_cents = excluded.compare_at_cents,
  active = true;
`;

writeFileSync(`${root}supabase/seed.sql`, sql);
console.log(`supabase/seed.sql: ${products.length} products`);
